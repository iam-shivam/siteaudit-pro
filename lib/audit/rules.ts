const always = (): Applicability => "applicable";

function feature(name: AuditFeature) {
  return (profile: SiteProfile): Applicability => {
    const value = profile.features[name];
    if (value === true) return "applicable";
    if (value === false) return "not_applicable";
    return "unknown";
  };
}

function anyFeature(...names: AuditFeature[]) {
  return (profile: SiteProfile): Applicability => {
    const values = names.map((name) => profile.features[name]);
    if (values.some((value) => value === true)) return "applicable";
    if (values.every((value) => value === false)) return "not_applicable";
    return "unknown";
  };
}

function siteTypes(...types: SiteProfile["siteType"][]) {
  return (profile: SiteProfile): Applicability =>
    types.includes(profile.siteType) ? "applicable" : "not_applicable";
}

interface BooleanRuleOptions {
  id: string;
  title: string;
  description: string;
  category: AuditCategory;
  pack: RulePack;
  signal: string;
  severity?: Severity;
  weight?: number;
  impact: string;
  remediation: string;
  effort?: Effort;
  owner?: ResponsibleRole;
  methods?: AssessmentMethod[];
  minimumEvidenceLevel?: 0 | 1 | 2 | 3 | 4 | 5 | 6;
  standards?: string[];
  applies?: (profile: SiteProfile) => Applicability;
  expected?: boolean;
}

function booleanRule(options: BooleanRuleOptions): RuleDefinition {
  const expected = options.expected ?? true;
  return {
    id: options.id,
    version: RULE_VERSION,
    title: options.title,
    description: options.description,
    category: options.category,
    pack: options.pack,
    observationKey: options.signal,
    severity: options.severity ?? "medium",
    weight: options.weight ?? 1,
    impact: options.impact,
    remediation: options.remediation,
    effort: options.effort ?? "medium",
    owner: options.owner ?? "developer",
    standardRefs: options.standards,
    methods: options.methods ?? ["public_observation"],
    minimumEvidenceLevel: options.minimumEvidenceLevel ?? 2,
    applies: options.applies ?? always,
    evaluate: (observation: Observation) => ({
      passed: observation.value === expected,
      summary:
        observation.note ??
        (observation.value === expected
          ? "The expected control was observed."
          : "The expected control was not observed."),
    }),
  };
}

interface MaximumRuleOptions extends Omit<BooleanRuleOptions, "expected"> {
  maximum: number;
  unit: string;
}

function maximumRule(options: MaximumRuleOptions): RuleDefinition {
  return {
    ...booleanRule(options),
    evaluate: (observation) => {
      const value = Number(observation.value);
      return {
        passed: Number.isFinite(value) && value <= options.maximum,
        summary: Number.isFinite(value)
          ? `${value}${options.unit} observed; target is at most ${options.maximum}${options.unit}.`
          : `A valid ${options.unit} measurement was not available.`,
        confidence: Number.isFinite(value) ? "high" : "low",
      };
    },
  };
}

